// Initialize from URL parameters
(function initFromUrl() {
  const params = new URLSearchParams(window.location.search);
  const initialSubject = params.get("subject");
  const initialGrade = params.get("grade");
  const initialTopic = params.get("topic");
  const initialQuery = params.get("q");

  if (initialQuery && lessonSearchInput) {
    lessonSearchInput.value = initialQuery;
    state.searchQuery = initialQuery;
    if (clearSearchBtn) clearSearchBtn.hidden = false;
  }

  if (initialSubject && SUBJECT_LABELS[initialSubject]) {
    selectSubject(initialSubject);
    if (initialGrade && ["5", "6", "7", "8", "9"].includes(initialGrade)) {
      selectGrade(initialGrade);
    }
    if (initialTopic && LESSONS.some((l) => l.id === initialTopic)) {
      selectTopic(initialTopic);
    }
  } else if (initialQuery) {
    renderLessons();
  } else {
    updateProgressIndicator();
    updateOverallProgressStats();
  }
  booting = false;
})();

// Listen for YouTube video ended message to unlock quiz
window.addEventListener("message", (event) => {
  if (event.origin !== "https://www.youtube-nocookie.com") return;
  try {
    const data = typeof event.data === "string" ? JSON.parse(event.data) : event.data;
    if (data?.event !== "onStateChange" || data.info !== 0) return;
    document.querySelectorAll(".lesson-card iframe").forEach((iframe) => {
      if (iframe.contentWindow === event.source) {
        const lessonId = iframe.closest(".lesson-card")?.querySelector(".quiz-unlock-btn")?.dataset.unlock;
        if (lessonId) openQuizAfterVideo(lessonId);
      }
    });
  } catch {}
});

