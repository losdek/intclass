/**
 * Filter lessons based on state, search query, and filter tab
 */
function getFilteredLessons() {
  const query = state.searchQuery.trim().toLowerCase();
  const completedSet = getProgressSet();
  const bookmarksSet = getBookmarksSet();

  return LESSONS.filter((l) => {
    // 1. Text search filter
    if (query) {
      const matchText =
        l.title.toLowerCase().includes(query) ||
        l.topic.toLowerCase().includes(query) ||
        l.description.toLowerCase().includes(query) ||
        (l.takeaway && l.takeaway.toLowerCase().includes(query)) ||
        (SUBJECT_LABELS[l.subject] && SUBJECT_LABELS[l.subject].toLowerCase().includes(query)) ||
        (l.quiz && l.quiz.some((q) => q.question.toLowerCase().includes(query)));
      if (!matchText) return false;
    } else {
      // Step-by-step filters if no search query
      if (state.subject && l.subject !== state.subject) return false;
      if (state.grade && l.grade !== state.grade) return false;
      if (state.topic && l.id !== state.topic) return false;
    }

    // 2. Tab filter (All / Uncompleted / Completed / Favorites)
    if (state.activeFilter === "completed" && !completedSet.has(l.id)) return false;
    if (state.activeFilter === "uncompleted" && completedSet.has(l.id)) return false;
    if (state.activeFilter === "favorites" && !bookmarksSet.has(l.id)) return false;
    if (state.activeFilter === "video" && !(l.video || l.videoId)) return false;

    return true;
  });
}

/**
 * Render topic filter chips
 */
function renderTopics() {
  if (!state.subject) {
    topicStep?.classList.add("is-locked");
    if (topicChoices) topicChoices.innerHTML = "";
    if (topicHint) topicHint.hidden = false;
    return;
  }

  const available = LESSONS.filter((l) => {
    const matchSub = l.subject === state.subject;
    const matchGrade = !state.grade || l.grade === state.grade;
    return matchSub && matchGrade;
  });

  if (available.length === 0) {
    if (topicChoices) {
      topicChoices.innerHTML = `<p class="flow-hint">Для выбранного класса уроки скоро появятся.</p>`;
    }
    return;
  }

  const topicChips = available
    .map((l) => {
      const isSelected = state.topic === l.id;
      const label = state.grade ? l.topic || l.title : `${l.grade} кл · ${l.topic || l.title}`;
      return `<button class="topic-chip ${isSelected ? "selected" : ""}" type="button" data-topic="${l.id}">${label}</button>`;
    })
    .join("");

  if (topicChoices) topicChoices.innerHTML = topicChips;
  topicStep?.classList.remove("is-locked");
  if (topicHint) topicHint.hidden = true;
  updateProgressIndicator();
}

/**
 * Render filtered lessons without choppy screen tearing
 */
function renderLessons() {
  const hasSearch = Boolean(state.searchQuery.trim());

  // Show results panel if subject selected or search query entered
  if (!state.subject && !hasSearch && state.activeFilter === "all") {
    resultsPanel?.classList.add("is-locked");
    return;
  }

  const filtered = getFilteredLessons();

  let headingText = "";
  if (hasSearch) {
    headingText = `Результаты поиска: «${state.searchQuery}» (${filtered.length})`;
  } else if (state.activeFilter === "favorites") {
    headingText = `Избранные уроки (${filtered.length})`;
  } else if (state.activeFilter === "video") {
    headingText = `Видеоуроки (${filtered.length})`;
  } else if (state.activeFilter === "completed") {
    headingText = `Пройденные уроки (${filtered.length})`;
  } else {
    const subjectTitle = SUBJECT_LABELS[state.subject] || "Все предметы";
    const gradeTitle = state.grade ? ` · ${state.grade} класс` : " · Все классы (5–9)";
    headingText = `${subjectTitle}${gradeTitle} (${filtered.length} ${filtered.length === 1 ? "урок" : "уроков"})`;
  }

  if (resultsTitle) {
    resultsTitle.textContent = headingText;
  }

  if (grid) {
    grid.innerHTML = "";
    filtered.forEach((lesson) => {
      grid.appendChild(createCard(lesson));
    });
  }

  if (empty) {
    empty.hidden = filtered.length > 0;
    if (filtered.length === 0) {
      empty.textContent = hasSearch
        ? `По запросу «${state.searchQuery}» ничего не найдено. Попробуйте другой запрос или сбросьте фильтры.`
        : state.activeFilter === "favorites"
        ? "В закладках пока пусто. Нажмите звёздочку ★ на любом уроке, чтобы сохранить его сюда."
        : "Для выбранной комбинации уроков не найдено.";
    }
  }

  resultsPanel?.classList.remove("is-locked");
  updateProgressIndicator();
  updateOverallProgressStats();
  updateUrl();
}

/**
 * Video player: native <video> for self-hosted lessons, YouTube embed for legacy ids
 */
function playVideo(media) {
  const src = media.dataset.src;
  const videoId = media.dataset.video;
  if (!src && !videoId) return;
  if (media.querySelector("video, iframe")) return;

  const card = media.closest(".lesson-card");
  const statusBox = card?.querySelector(".quiz-lock-status");

  if (src) {
    const poster = media.querySelector("img")?.getAttribute("src") || "";
    media.innerHTML = `<video src="${src}" poster="${poster}" controls autoplay playsinline preload="auto"></video>`;
    const video = media.querySelector("video");
    video.addEventListener("play", () => {
      // only one lesson plays at a time
      document.querySelectorAll(".lesson-media video").forEach((other) => {
        if (other !== video) other.pause();
      });
    });
    video.addEventListener("ended", () => {
      const lessonId = card?.querySelector(".lesson-quiz")?.dataset.lessonId;
      if (lessonId) unlockQuiz(lessonId, true);
    });
    video.play()?.catch(() => {});
  } else {
    media.innerHTML = `<iframe src="https://www.youtube-nocookie.com/embed/${videoId}?autoplay=1&enablejsapi=1&rel=0&origin=${encodeURIComponent(location.origin)}" title="Видеоурок YouTube" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture" allowfullscreen></iframe>`;
  }
  media.style.cursor = "default";

  if (statusBox) {
    const textElem = statusBox.querySelector(".quiz-lock-text");
    const iconElem = statusBox.querySelector(".quiz-lock-icon");
    if (textElem) textElem.textContent = "Идёт видеоурок. Тест откроется по завершении";
    if (iconElem) iconElem.textContent = "▶";
  }
}

/**
 * Unlock Quiz smoothly on demand or after video completion
 */
function unlockQuiz(lessonId, smoothScroll = false) {
  const quizElem = document.querySelector(`.lesson-quiz[data-lesson-id="${lessonId}"]`);
  if (!quizElem) return;

  const card = quizElem.closest(".lesson-card");
  const statusBox = card?.querySelector(".quiz-lock-status");
  const quizBox = quizElem.querySelector(".quiz-box");
  const toggleBtn = quizElem.querySelector(".quiz-toggle-btn");

  if (statusBox) statusBox.hidden = true;
  quizElem.hidden = false;

  if (quizBox) {
    quizBox.hidden = false;
    if (toggleBtn) {
      toggleBtn.textContent = "Свернуть тест";
      toggleBtn.setAttribute("aria-expanded", "true");
    }
  }

  if (smoothScroll) {
    quizElem.scrollIntoView({ behavior: "smooth", block: "nearest" });
  }
}

/**
 * Interactive Quiz grading & interactions
 */
function handleQuizInteraction(event) {
  const target = event.target;

  // 1. Direct Unlock Button
  const unlockBtn = target.closest(".quiz-unlock-btn");
  if (unlockBtn) {
    const lessonId = unlockBtn.dataset.unlock;
    unlockQuiz(lessonId, true);
    return;
  }

  // 2. Collapse / Expand Quiz
  const toggleBtn = target.closest(".quiz-toggle-btn");
  if (toggleBtn) {
    const quizBox = toggleBtn.closest(".lesson-quiz")?.querySelector(".quiz-box");
    if (quizBox) {
      const isHidden = quizBox.hidden;
      quizBox.hidden = !isHidden;
      toggleBtn.textContent = isHidden ? "Свернуть тест" : "Развернуть тест";
      toggleBtn.setAttribute("aria-expanded", String(isHidden));
    }
    return;
  }

  // 3. Radio Option Selection
  const optionInput = target.closest('input[type="radio"]');
  if (optionInput) {
    const question = optionInput.closest(".quiz-question-item");
    if (question) {
      question.querySelectorAll(".quiz-option-label").forEach((label) => {
        label.classList.toggle("checked", label.contains(optionInput));
      });
    }
    return;
  }

  // 4. Check Answers
  const checkBtn = target.closest(".quiz-check-btn");
  if (checkBtn) {
    const quizElem = checkBtn.closest(".lesson-quiz");
    const lessonId = quizElem?.dataset.lessonId;
    const lesson = LESSONS.find((l) => l.id === lessonId);
    if (!lesson || !lesson.quiz) return;

    const resultMsg = quizElem.querySelector(".quiz-result-msg");
    const retryBtn = quizElem.querySelector(".quiz-retry-btn");
    const questions = quizElem.querySelectorAll(".quiz-question-item");

    // a radio question answers with the option index, an interactive task with its widget value
    const answers = [...questions].map((qElem) => {
      const task = qElem.querySelector(".task")?.taskCtrl;
      if (task) return task.value();
      const selected = qElem.querySelector('input[type="radio"]:checked');
      return selected ? Number(selected.value) : null;
    });
    const allAnswered = answers.every((a) => a !== null);
    let correctCount = 0;

    if (allAnswered) {
      questions.forEach((qElem, qIdx) => {
        const q = lesson.quiz[qIdx];
        const userVal = answers[qIdx];
        const task = qElem.querySelector(".task")?.taskCtrl;

        if (task) {
          const ok = window.IntTasks.check(q, userVal);
          qElem.classList.add(ok ? "is-correct" : "is-wrong");
          if (!ok) task.reveal();
          task.lock(true);
          if (ok) correctCount++;
          return;
        }

        qElem.querySelectorAll(".quiz-option-label").forEach((label) => {
          const lIdx = Number(label.dataset.opt);
          label.classList.remove("is-correct", "is-wrong");
          if (lIdx === q.answer) {
            label.classList.add("is-correct");
          } else if (lIdx === userVal) {
            label.classList.add("is-wrong");
          }
        });
        if (userVal === q.answer) correctCount++;
      });
    }

    if (!allAnswered) {
      if (resultMsg) {
        resultMsg.hidden = false;
        resultMsg.className = "quiz-result-msg info";
        resultMsg.textContent = "Пожалуйста, ответьте на все вопросы и выполните задания перед проверкой.";
      }
      return;
    }

    if (resultMsg) {
      resultMsg.hidden = false;
      const explanations = lesson.quiz.map((q, idx) => `Вопрос ${idx + 1}: ${q.explanation}`).join(" ");

      if (correctCount === questions.length) {
        resultMsg.className = "quiz-result-msg success";
        resultMsg.textContent = `✓ Отлично! Все ответы верны (${correctCount} из ${questions.length}). ${explanations}`;
        saveProgress(lesson.id);
        launchConfetti();
        if (typeof window.showToast === "function") {
          window.showToast("Поздравляем! Урок и тест успешно пройдены 🎉", "success");
        }
        const card = quizElem.closest(".lesson-card");
        if (card && !card.querySelector(".lesson-completed-ribbon")) {
          card.classList.add("is-completed");
          const media = card.querySelector(".lesson-media");
          if (media) {
            const ribbon = document.createElement("div");
            ribbon.className = "lesson-completed-ribbon";
            ribbon.textContent = "✓ Изучено";
            media.appendChild(ribbon);
          }
        }
        updateOverallProgressStats();
      } else {
        resultMsg.className = "quiz-result-msg error";
        resultMsg.textContent = `Результат: ${correctCount} из ${questions.length}. Правильные ответы подсвечены зелёным, в заданиях показано верное решение. ${explanations}`;
      }
      checkBtn.hidden = true;
      if (retryBtn) retryBtn.hidden = false;
    }
    return;
  }

  // 5. Retry Quiz
  const retryBtn = target.closest(".quiz-retry-btn");
  if (retryBtn) {
    const quizElem = retryBtn.closest(".lesson-quiz");
    const checkBtn = quizElem?.querySelector(".quiz-check-btn");
    const resultMsg = quizElem?.querySelector(".quiz-result-msg");

    if (quizElem) {
      quizElem.querySelectorAll('input[type="radio"]').forEach((input) => {
        input.checked = false;
      });
      quizElem.querySelectorAll(".quiz-option-label").forEach((label) => {
        label.classList.remove("checked", "is-correct", "is-wrong");
      });
      quizElem.querySelectorAll(".quiz-question-item").forEach((item) => {
        item.classList.remove("is-correct", "is-wrong");
        item.querySelector(".task")?.taskCtrl?.reset();
      });
    }

    if (resultMsg) resultMsg.hidden = true;
    if (checkBtn) checkBtn.hidden = false;
    retryBtn.hidden = true;
  }
}

/**
 * Handle card actions (Bookmark toggle & Share copy link)
 */
function handleCardAction(event) {
  // Bookmark toggle
  const bookmarkBtn = event.target.closest("[data-bookmark]");
  if (bookmarkBtn) {
    event.stopPropagation();
    const lessonId = bookmarkBtn.dataset.bookmark;
    const isNowSaved = toggleBookmark(lessonId);
    bookmarkBtn.classList.toggle("active", isNowSaved);
    const icon = bookmarkBtn.querySelector(".bookmark-icon");
    if (icon) icon.textContent = isNowSaved ? "★" : "☆";
    bookmarkBtn.setAttribute("title", isNowSaved ? "В избранном" : "В закладки");

    if (typeof window.showToast === "function") {
      window.showToast(isNowSaved ? "Урок добавлен в избранное ★" : "Урок удалён из избранного", "info");
    }

    if (state.activeFilter === "favorites") {
      renderLessons();
    }
    return true;
  }

  // Share link copy
  const shareBtn = event.target.closest("[data-share]");
  if (shareBtn) {
    event.stopPropagation();
    const lessonId = shareBtn.dataset.share;
    const lesson = LESSONS.find((l) => l.id === lessonId);
    if (!lesson) return true;

    const shareUrl = `${location.origin}${location.pathname}?subject=${lesson.subject}&grade=${lesson.grade}&topic=${lesson.id}`;

    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard
        .writeText(shareUrl)
        .then(() => {
          if (typeof window.showToast === "function") {
            window.showToast("Ссылка на урок скопирована в буфер!", "success");
          }
        })
        .catch(() => {
          prompt("Скопируйте ссылку на урок:", shareUrl);
        });
    } else {
      prompt("Скопируйте ссылку на урок:", shareUrl);
    }
    return true;
  }

  return false;
}

/**
 * Step Selection Functions
 */
function selectSubject(subject) {
  state.subject = subject;
  state.topic = null;

  document.querySelectorAll("[data-subject]").forEach((button) => {
    button.classList.toggle("selected", button.dataset.subject === subject);
  });

  gradeStep?.classList.remove("is-locked");
  if (gradeHint) gradeHint.hidden = true;

  document.querySelectorAll("[data-grade]").forEach((btn) => {
    const isSelected = (!state.grade && btn.dataset.grade === "all") || btn.dataset.grade === state.grade;
    btn.classList.toggle("selected", isSelected);
  });

  renderTopics();
  renderLessons();
}

function selectGrade(gradeVal) {
  if (!state.subject) return;

  state.grade = gradeVal === "all" || !gradeVal ? null : gradeVal;
  state.topic = null;

  document.querySelectorAll("[data-grade]").forEach((btn) => {
    const isSelected = (!state.grade && btn.dataset.grade === "all") || btn.dataset.grade === state.grade;
    btn.classList.toggle("selected", isSelected);
  });

  renderTopics();
  renderLessons();
}

function selectTopic(topicVal) {
  if (state.topic === topicVal) {
    state.topic = null;
  } else {
    state.topic = topicVal;
  }

  topicChoices?.querySelectorAll(".topic-chip").forEach((btn) => {
    btn.classList.toggle("selected", btn.dataset.topic === state.topic);
  });

  renderLessons();

  if (state.topic) {
    const targetCard = document.getElementById(`card-${state.topic}`);
    if (targetCard) {
      targetCard.scrollIntoView({ behavior: "smooth", block: "nearest" });
      const media = targetCard.querySelector(".lesson-media");
      if (media && !media.querySelector("iframe, video")) {
        playVideo(media);
      }
    }
  }
}

