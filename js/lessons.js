// Event Listeners: Search input & Clear
let searchDebounceTimeout = null;
if (lessonSearchInput) {
  lessonSearchInput.addEventListener("input", () => {
    clearTimeout(searchDebounceTimeout);
    searchDebounceTimeout = setTimeout(() => {
      state.searchQuery = lessonSearchInput.value.trim();
      if (clearSearchBtn) {
        clearSearchBtn.hidden = !state.searchQuery;
      }
      renderLessons();
    }, 180);
  });

  clearSearchBtn?.addEventListener("click", () => {
    lessonSearchInput.value = "";
    state.searchQuery = "";
    clearSearchBtn.hidden = true;
    renderLessons();
    lessonSearchInput.focus();
  });

  // Shortcut '/' or 'Ctrl+K' to focus search
  document.addEventListener("keydown", (e) => {
    if (
      (e.key === "/" && document.activeElement !== lessonSearchInput && !["INPUT", "TEXTAREA"].includes(document.activeElement.tagName)) ||
      ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === "k")
    ) {
      e.preventDefault();
      lessonSearchInput.focus();
      lessonSearchInput.scrollIntoView({ behavior: "smooth", block: "center" });
    } else if (e.key === "Escape" && document.activeElement === lessonSearchInput) {
      lessonSearchInput.blur();
    }
  });
}

