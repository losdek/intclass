/**
 * Filter lessons based on state, search query, and filter tab
 */
function getFilteredLessons() {
  const query = state.searchQuery.trim().toLowerCase();
  const completedSet = getProgressSet();
  const bookmarksSet = getBookmarksSet();

  return LESSONS.filter((l) => {
    // 1. Text search filter
    if (query) {
      const matchText =
        l.title.toLowerCase().includes(query) ||
        l.topic.toLowerCase().includes(query) ||
        l.description.toLowerCase().includes(query) ||
        (l.takeaway && l.takeaway.toLowerCase().includes(query)) ||
        (SUBJECT_LABELS[l.subject] && SUBJECT_LABELS[l.subject].toLowerCase().includes(query)) ||
        (l.quiz && l.quiz.some((q) => q.question.toLowerCase().includes(query)));
      if (!matchText) return false;
    } else {
      // Step-by-step filters if no search query
      if (state.subject && l.subject !== state.subject) return false;
      if (state.grade && l.grade !== state.grade) return false;
      if (state.topic && l.id !== state.topic) return false;
    }

    // 2. Tab filter (All / Uncompleted / Completed / Favorites)
    if (state.activeFilter === "completed" && !completedSet.has(l.id)) return false;
    if (state.activeFilter === "uncompleted" && completedSet.has(l.id)) return false;
    if (state.activeFilter === "favorites" && !bookmarksSet.has(l.id)) return false;
    if (state.activeFilter === "video" && !(l.video || l.videoId)) return false;

    return true;
  });
}

/**
 * Render topic filter chips
 */
function renderTopics() {
  if (!state.subject) {
    topicStep?.classList.add("is-locked");
    if (topicChoices) topicChoices.innerHTML = "";
    return;
  }

  const available = LESSONS.filter((l) => {
    const matchSub = l.subject === state.subject;
    const matchGrade = !state.grade || l.grade === state.grade;
    return matchSub && matchGrade;
  });

  if (available.length === 0) {
    if (topicChoices) {
      topicChoices.innerHTML = `<p class="flow-hint">Для выбранного класса уроки скоро появятся.</p>`;
    }
    return;
  }

  const topicChips = available
    .map((l) => {
      const isSelected = state.topic === l.id;
      const label = state.grade ? l.topic || l.title : `${l.grade} кл · ${l.topic || l.title}`;
      return `<button class="topic-chip ${isSelected ? "selected" : ""}" type="button" data-topic="${l.id}">${label}</button>`;
    })
    .join("");

  if (topicChoices) topicChoices.innerHTML = topicChips;
  topicStep?.classList.remove("is-locked");
  updateProgressIndicator();
}

/**
 * Render filtered lessons without choppy screen tearing
 */
function renderLessons() {
  const hasSearch = Boolean(state.searchQuery.trim());

  // Show results panel if subject selected or search query entered
  if (!state.subject && !hasSearch && state.activeFilter === "all") {
    resultsPanel?.classList.add("is-locked");
    return;
  }

  const filtered = getFilteredLessons();

  let headingText = "";
  if (hasSearch) {
    headingText = `Результаты поиска: «${state.searchQuery}» (${filtered.length})`;
  } else if (state.activeFilter === "favorites") {
    headingText = `Избранные уроки (${filtered.length})`;
  } else if (state.activeFilter === "video") {
    headingText = `Видеоуроки (${filtered.length})`;
  } else if (state.activeFilter === "completed") {
    headingText = `Пройденные уроки (${filtered.length})`;
  } else {
    const subjectTitle = SUBJECT_LABELS[state.subject] || "Все предметы";
    const gradeTitle = state.grade ? ` · ${state.grade} класс` : " · Все классы (5–9)";
    headingText = `${subjectTitle}${gradeTitle} (${filtered.length} ${filtered.length === 1 ? "урок" : "уроков"})`;
  }

  if (resultsTitle) {
    resultsTitle.textContent = headingText;
  }

  if (grid) {
    grid.innerHTML = "";
    filtered.forEach((lesson) => {
      grid.appendChild(createCard(lesson));
    });
  }

  if (empty) {
    empty.hidden = filtered.length > 0;
    if (filtered.length === 0) {
      empty.textContent = hasSearch
        ? `По запросу «${state.searchQuery}» ничего не найдено. Попробуйте другой запрос или сбросьте фильтры.`
        : state.activeFilter === "favorites"
        ? "В закладках пока пусто. Нажмите звёздочку ★ на любом уроке, чтобы сохранить его сюда."
        : "Для выбранной комбинации уроков не найдено.";
    }
  }

  resultsPanel?.classList.remove("is-locked");
  updateProgressIndicator();
  updateOverallProgressStats();
  updateUrl();
}

/**
 * Video player: native <video> for self-hosted lessons, YouTube embed for legacy ids
 */
function playVideo(media) {
  const src = media.dataset.src;
  const videoId = media.dataset.video;
  if (!src && !videoId) return;
  if (media.querySelector("video, iframe")) return;

  const card = media.closest(".lesson-card");
  const statusBox = card?.querySelector(".quiz-lock-status");

  if (src) {
    const poster = media.querySelector("img")?.getAttribute("src") || "";
    media.innerHTML = `<video src="${src}" poster="${poster}" controls autoplay playsinline preload="auto"></video>`;
    const video = media.querySelector("video");
    video.addEventListener("play", () => {
      // only one lesson plays at a time
      document.querySelectorAll(".lesson-media video").forEach((other) => {
        if (other !== video) other.pause();
      });
    });
    video.addEventListener("ended", () => {
      const lessonId = card?.querySelector(".quiz-unlock-btn")?.dataset.unlock;
      if (lessonId) openQuizAfterVideo(lessonId);
    });
    video.play()?.catch(() => {});
  } else {
    media.innerHTML = `<iframe src="https://www.youtube-nocookie.com/embed/${videoId}?autoplay=1&enablejsapi=1&rel=0&origin=${encodeURIComponent(location.origin)}" title="Видеоурок YouTube" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture" allowfullscreen></iframe>`;
  }
  media.style.cursor = "default";

  if (statusBox) {
    const textElem = statusBox.querySelector(".quiz-lock-text");
    const iconElem = statusBox.querySelector(".quiz-lock-icon");
    if (textElem) textElem.textContent = "Идёт видеоурок. Тест откроется по завершении";
    if (iconElem) iconElem.textContent = "▶";
  }
}

