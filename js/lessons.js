/**
 * Handle card actions (Bookmark toggle & Share copy link)
 */
function handleCardAction(event) {
  // Bookmark toggle
  const bookmarkBtn = event.target.closest("[data-bookmark]");
  if (bookmarkBtn) {
    event.stopPropagation();
    const lessonId = bookmarkBtn.dataset.bookmark;
    const isNowSaved = toggleBookmark(lessonId);
    bookmarkBtn.classList.toggle("active", isNowSaved);
    const icon = bookmarkBtn.querySelector(".bookmark-icon");
    if (icon) icon.textContent = isNowSaved ? "★" : "☆";
    bookmarkBtn.setAttribute("title", isNowSaved ? "В избранном" : "В закладки");

    if (typeof window.showToast === "function") {
      window.showToast(isNowSaved ? "Урок добавлен в избранное ★" : "Урок удалён из избранного", "info");
    }

    if (state.activeFilter === "favorites") {
      renderLessons();
    }
    return true;
  }

  // Share link copy
  const shareBtn = event.target.closest("[data-share]");
  if (shareBtn) {
    event.stopPropagation();
    const lessonId = shareBtn.dataset.share;
    const lesson = LESSONS.find((l) => l.id === lessonId);
    if (!lesson) return true;

    const shareUrl = `${location.origin}${location.pathname}?subject=${lesson.subject}&grade=${lesson.grade}&topic=${lesson.id}`;

    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard
        .writeText(shareUrl)
        .then(() => {
          if (typeof window.showToast === "function") {
            window.showToast("Ссылка на урок скопирована в буфер!", "success");
          }
        })
        .catch(() => {
          prompt("Скопируйте ссылку на урок:", shareUrl);
        });
    } else {
      prompt("Скопируйте ссылку на урок:", shareUrl);
    }
    return true;
  }

  return false;
}

/**
 * Step Selection Functions
 */
function selectSubject(subject) {
  state.subject = subject;
  state.topic = null;

  document.querySelectorAll("[data-subject]").forEach((button) => {
    button.classList.toggle("selected", button.dataset.subject === subject);
  });

  gradeStep?.classList.remove("is-locked");

  document.querySelectorAll("[data-grade]").forEach((btn) => {
    const isSelected = (!state.grade && btn.dataset.grade === "all") || btn.dataset.grade === state.grade;
    btn.classList.toggle("selected", isSelected);
  });

  if (gradeHint) gradeHint.textContent = `${SUBJECT_LABELS[subject]} — выберите класс`;
  renderTopics();
  renderLessons();
  showPane(2);
}

function selectGrade(gradeVal) {
  if (!state.subject) return;

  state.grade = gradeVal === "all" || !gradeVal ? null : gradeVal;
  state.topic = null;

  document.querySelectorAll("[data-grade]").forEach((btn) => {
    const isSelected = (!state.grade && btn.dataset.grade === "all") || btn.dataset.grade === state.grade;
    btn.classList.toggle("selected", isSelected);
  });

  if (topicHint) {
    topicHint.textContent = `${SUBJECT_LABELS[state.subject]} · ${state.grade ? `${state.grade} класс` : "все классы"} — выберите тему, откроется видео и тест`;
  }
  renderTopics();
  renderLessons();
  showPane(3);
}

function selectTopic(topicVal) {
  if (state.topic === topicVal) {
    state.topic = null;
  } else {
    state.topic = topicVal;
  }

  topicChoices?.querySelectorAll(".topic-chip").forEach((btn) => {
    btn.classList.toggle("selected", btn.dataset.topic === state.topic);
  });

  renderLessons();

  if (state.topic) {
    const targetCard = document.getElementById(`card-${state.topic}`);
    if (targetCard) {
      targetCard.scrollIntoView({ behavior: "smooth", block: "nearest" });
      const media = targetCard.querySelector(".lesson-media");
      if (media && !media.querySelector("iframe, video")) {
        playVideo(media);
      }
    }
  }
}

